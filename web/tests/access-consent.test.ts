import { afterAll, beforeAll, expect, it } from "vitest";
import { closeTestDb, openTestDb, seedWorkspace, type Db } from "./helpers/testdb";
let db: Db;
let guard: typeof import("../src/server/guard");
let pub: typeof import("../src/server/public");
let ledger: typeof import("../src/server/ledger");
let ctx: Awaited<ReturnType<typeof seedWorkspace>>;
const token = "abcdefghijklmnopqrstuvwx";
beforeAll(async () => {
 db = await openTestDb(); ctx = await seedWorkspace(db,"wa","ua","pa"); await seedWorkspace(db,"wb","ub","pb");
 guard = await import("../src/server/guard"); pub = await import("../src/server/public"); ledger = await import("../src/server/ledger");
 const crypto = await import("../src/server/crypto");
 (await db.run(`INSERT INTO person (id,workspace_id,project_id,name,role,created_at) VALUES ('person','wa','pa','Thandi','guest',0)`));
 (await db.run(`INSERT INTO consent (id,workspace_id,project_id,person_id,scope,status,statement,requested_by,requested_at,updated_at) VALUES ('consent','wa','pa','person','appearance','requested','Use appearance','ua',0,0)`));
 (await db.run(`INSERT INTO person (id,workspace_id,project_id,name,role,created_at) VALUES ('person2','wa','pa','Lebo','guest',0)`));
 (await db.run(`INSERT INTO consent (id,workspace_id,project_id,person_id,scope,status,statement,requested_by,requested_at,updated_at) VALUES ('consent2','wa','pa','person2','appearance','requested','Use appearance','ua',0,0)`));
 (await db.run(`INSERT INTO declaration (id,workspace_id,project_id,user_id,statement,created_at) VALUES ('dec','wa','pa','ua','Declared',0)`));
 (await db.run(`INSERT INTO clip (id,workspace_id,project_id,title,start_ms,end_ms,reason,origin,status,created_at,updated_at) VALUES ('clip','wa','pa','Clip',0,1000,'test','manual','kept',0,0)`));
 (await db.run(`INSERT INTO share_link (id,workspace_id,project_id,purpose,target_id,token_hash,expires_at,created_by,created_at) VALUES ('link','wa','pa','consent','consent',?,?, 'ua',0)`,crypto.hashToken(token),Date.now()+60000));
 (await db.run(`INSERT INTO share_link (id,workspace_id,project_id,purpose,target_id,token_hash,expires_at,created_by,created_at) VALUES ('link2','wa','pa','consent','consent2',?,?, 'ua',0)`,crypto.hashToken("zyxwvutsrqponmlkjihgfedc"),Date.now()+60000));
 for (const [id,status,posted] of [["held","blocked",null],["ready","ready",null],["posted","ready",1]] as const) (await db.run(`INSERT INTO output (id,workspace_id,project_id,clip_id,preset,status,posted_at,created_by,created_at,updated_at) VALUES (?, 'wa','pa','clip','test',?,?, 'ua',0,0)`,id,status,posted));
},60000);
afterAll(async () => await closeTestDb(db));
it("scopes projects to the workspace and enforces allowed roles", async () => {
 expect((await guard.projectOf(ctx,"pa")).id).toBe("pa");
 await expect(guard.projectOf(ctx,"pb")).rejects.toThrow(expect.objectContaining({status:404}));
 expect(() => guard.requireRole(ctx,["owner","admin"])).not.toThrow();
 await expect(guard.requireRole({...ctx,role:"member"},["owner","admin"])).rejects.toThrow(expect.objectContaining({status:403}));
});
it("checks purpose, expiry and revocation", async () => {
 expect((await pub.linkFor(token,"consent")).id).toBe("link");
 await expect(pub.linkFor(token,"review")).rejects.toThrow(expect.objectContaining({status:404}));
 await expect(pub.linkFor("bad","consent")).rejects.toThrow(expect.objectContaining({status:404}));
 (await db.run(`UPDATE share_link SET expires_at = ? WHERE id='link'`,Date.now()-1));
 await expect(pub.linkFor(token,"consent")).rejects.toThrow(expect.objectContaining({status:410}));
 (await db.run(`UPDATE share_link SET expires_at = ?, revoked_at = ? WHERE id='link'`,Date.now()+60000,Date.now()));
 await expect(pub.linkFor(token,"consent")).rejects.toThrow(expect.objectContaining({status:410}));
 (await db.run(`UPDATE share_link SET revoked_at = NULL WHERE id='link'`));
});
it("Ask again revokes the prior pending consent link and it returns 404", async () => {
 const actions = await import("../src/server/actions");
 const crypto = await import("../src/server/crypto");
 const oldToken = "oldaskagainconsentlink123456";
 (await db.run(`INSERT INTO person (id,workspace_id,project_id,name,role,created_at) VALUES ('ask_person','wa','pa','Ask Person','guest',0)`));
 (await db.run(`INSERT INTO consent (id,workspace_id,project_id,person_id,scope,status,statement,requested_by,requested_at,updated_at) VALUES ('ask_old','wa','pa','ask_person','appearance','requested','Use appearance','ua',1,1)`));
 (await db.run(`INSERT INTO share_link (id,workspace_id,project_id,purpose,target_id,token_hash,expires_at,created_by,created_at) VALUES ('ask_link','wa','pa','consent','ask_old',?,?, 'ua',0)`,crypto.hashToken(oldToken),Date.now()+60000));
 const result = (await actions.requestConsent(ctx, "pa", "ask_person", "voice"));
 expect(result.url).toContain("/c/");
 await expect(pub.linkFor(oldToken, "consent")).rejects.toThrow(expect.objectContaining({status:404}));
 await expect(pub.consentData(oldToken)).rejects.toThrow(expect.objectContaining({status:404}));
 (await db.run(`DELETE FROM person WHERE id = 'ask_person'`));
});
it("records consent and holds unpublished outputs after withdrawal", async () => {
 await expect(pub.consentAction(token,{decision:"grant",name:"Wrong"},"test","test")).rejects.toThrow(expect.objectContaining({status:400}));
 expect((await pub.consentAction(token,{decision:"grant",name:"Thandi"},"test","test"))).toEqual({status:"granted"});
 expect((await db.one<{status:string}>(`SELECT status FROM output WHERE id='held'`))?.status).toBe("blocked");
 expect((await pub.consentAction("zyxwvutsrqponmlkjihgfedc",{decision:"grant",name:"Lebo"},"test","test"))).toEqual({status:"granted"});
 expect((await db.one<{status:string}>(`SELECT status FROM output WHERE id='held'`))?.status).toBe("queued");
 expect((await pub.consentAction(token,{decision:"revoke",name:"Thandi"},"test","test"))).toEqual({status:"revoked"});
 for (const id of ["held","ready"]) expect((await db.one<{status:string}>(`SELECT status FROM output WHERE id=?`,id))?.status).toBe("blocked");
 expect((await db.one<{status:string}>(`SELECT status FROM output WHERE id='posted'`))?.status).toBe("ready");
 const records = (await db.all<{record:string}>(`SELECT record FROM consent_ledger ORDER BY seq`)).map(x => JSON.parse(x.record));
 expect(records.map(x => x.decision)).toEqual(["granted","granted","revoked"]);
 expect(records[0]).toMatchObject({workspaceId:"wa",projectId:"pa",consentId:"consent",scope:"appearance"});
 expect((await ledger.verifyLedger(new Set([ledger.ledgerKeys().pubHex])))).toMatchObject({ok:true,entries:3});
});
